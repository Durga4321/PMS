export function translateTelugu(text) {
  if (!/[a-z]/i.test(text)) return text
  if (cache.has(text)) return cache.get(text)
  const normalized = text.trim().replace(/\s+/g, ' ')
  const key = normalized.toLowerCase()
  const direct = phrases.get(key)
  let translated = direct
  if (!translated) {
    // Keep punctuation and numeric counters around a known UI label.
    const label = key.replace(/^[\s+*•:()–—]+|[\s*•:()!.,?–—]+$/g, '')
    const labelTranslation = phrases.get(label)
    if (labelTranslation) translated = normalized.replace(new RegExp(escapeRegex(label), 'i'), labelTranslation)
  }
  if (!translated) {
    for (const { pattern, target } of templatePatterns) {
      const match = normalized.match(pattern)
      if (match) {
        translated = target.replace(/\{(\d+)\}/g, (_, index) => phrases.get(match[Number(index) + 1].toLowerCase()) || match[Number(index) + 1])
        break
      }
    }
  }
  if (!translated && /^(?:[A-Za-z]{3,9},?\s+)?(?:\d{1,2}[\s/-]+[A-Za-z]{3,9}[\s,/-]+\d{2,4}|[A-Za-z]{3,9}\s+\d{1,2},?\s+\d{4})/.test(normalized)) {
    translated = normalized.replace(/\b[A-Za-z]+\b/g, (word) => phrases.get(word.toLowerCase()) || word)
  }
  const result = translated ? text.replace(text.trim(), translated) : text
  cache.set(text, result)
  return result
}

